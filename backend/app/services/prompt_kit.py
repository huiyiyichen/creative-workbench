    "- 结尾落在一个具体判断、行动或回扣开头的细节上；不用「综上所述」「总而言之」收尾，不写空洞祝福和号召。\n"
    "- 「不是 X，而是 Y」只在纠正一个读者真的会有的误解时用，全文最多一次；多数时候直接说 Y。\n"
