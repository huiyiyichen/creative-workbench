def platform_system(kind: str, label: str, json_shape: str) -> str:
    """平台改写的 system 提示词：角色 + 平台写法 + 信息守恒 + 中文约束 + 输出格式。"""
    return (
        f"你是{label}编辑，熟悉{label}读者的阅读习惯。任务：把作者已经定稿的文稿改写成适合{label}发布的版本，保留文稿的核心观点和全部关键事实，"
        f"按{label}读者的阅读习惯重新组织标题、开头、结构和语气。\n"
        + PLATFORM_PLAYBOOK.get(kind, "")
        + "\n"
        + INFO_CONSERVATION
        + "\n"
        + NO_FAKE_EXPERIENCE
        + "\n"
        + ZH_STYLE
        + "\n"
        + UNTRUSTED
        + f"\n<output>只返回一个 JSON 对象，不要代码围栏和解释：{json_shape}</output>"
    )


